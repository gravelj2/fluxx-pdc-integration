#!/usr/bin/env ruby
# Builds a READ-ONLY paste-in probe for choosing where configuration snapshots
# can live. It reports:
#   field   how previous_configuration is stored, and the largest value it
#           holds intact (binary search with saves that are always rolled back)
#   sizes   compressed snapshot size per component type, and per form
#   docs    how ModelDocument (and any other document class) stores files
#
#   ruby deploy/tools/build_one_off_probe.rb [OUT]   (default DEV/one-off-probe.rb)

require 'json'
require 'zlib'
require 'base64'

ROOT = File.expand_path('../..', __dir__)
out_path = File.expand_path(ARGV[0] || 'DEV/one-off-probe.rb', ROOT)

def strip_ruby(src)
  src.lines.reject { |l| l.strip.empty? || l =~ /\A\s*#/ }.join
end

bundle = JSON.generate(JSON.parse(File.read(File.join(ROOT, 'deploy/pdc-install-bundle.json'), encoding: 'UTF-8')))
packed = Base64.strict_encode64(Zlib::Deflate.deflate(bundle, Zlib::BEST_COMPRESSION))
lib = strip_ruby(File.read(File.join(ROOT, 'deploy/installer/PDC Installer Lib.rb'), encoding: 'UTF-8'))

script = +"# ONE-OFF PDC SNAPSHOT PROBE (generated by deploy/tools/build_one_off_probe.rb). Read-only: every test save is rolled back.\n"
script << "# The last line must be: probe_result\n"
script << "require 'json'\nrequire 'time'\nrequire 'zlib'\nrequire 'base64'\nrequire 'cgi'\n"
script << "pdc_bundle = JSON.parse(Zlib::Inflate.inflate(Base64.decode64(#{packed.inspect})).force_encoding('UTF-8'))\n"
script << lib
script << <<~'RUBY'
  probe_result =
    begin
      out = {}
      kb = lambda { |s| (s.bytesize / 1024.0).round(1) }
      cols = lambda do |klass|
        klass.columns.map { |c| "#{c.name}:#{c.sql_type}" }
      end

      # 1. Where previous_configuration lives, and its real limit
      f = {}
      f['is_column_on_model_table'] = model.class.column_names.include?('previous_configuration')
      f['model_table'] = model.class.table_name
      if f['is_column_on_model_table']
        f['sql_type'] = model.class.columns_hash['previous_configuration'].sql_type
      end
      attr = ModelAttribute.where(model_type: model.class.name, name: 'previous_configuration', deleted_at: nil).first
      f['model_attribute'] = attr && attr.attributes.slice('id', 'attribute_type', 'multi_allowed')
      %w[ModelAttributeChoice].each do |k|
        f["#{k}_columns"] = (cols.call(Object.const_get(k)) rescue 'n/a')
      end
      lo, hi = 0, 16 * 1024 * 1024
      probe = lambda { |n| lib[:fits].call(model, 'previous_configuration', 'x' * n) rescue false }
      if probe.call(hi)
        f['max_intact_bytes'] = ">= #{hi}"
      else
        while hi - lo > 1
          mid = (lo + hi) / 2
          probe.call(mid) ? lo = mid : hi = mid
        end
        f['max_intact_bytes'] = lo
      end
      out['field'] = f

      # 2. Snapshot size by component type and per form
      snap = lib[:take_snapshot].call(lib[:snapshot_targets].call(pdc_bundle), 'probe')
      total = lib[:snapshot_value].call(snap)
      sizes = { 'total_kb' => kb.call(total) }
      snap['records'].group_by { |r| r['table'] }.each do |table, recs|
        sizes[table] = { 'count' => recs.size, 'kb' => kb.call(lib[:pack_export].call(recs)) }
      end
      sizes['forms'] = snap['records'].select { |r| r['table'] == 'Stencil' && r['cols'] }.map do |r|
        st = Stencil.find_by(id: r['find']['id'])
        json = r['cols']['json'].to_s
        { 'id' => r['find']['id'], 'model_type' => st&.model_type, 'name' => st&.name.to_s.strip,
          'raw_kb' => kb.call(json), 'packed_kb' => kb.call(lib[:pack_export].call(json)),
          'elements' => lib[:stencil_elements].call(json).size }
      end
      out['sizes'] = sizes

      # 3. Document storage
      docs = {}
      candidates = %w[ModelDocument Document ModelDocumentType ModelDocumentTemplate].select { |k| Object.const_defined?(k) rescue false }
      candidates.each do |k|
        klass = Object.const_get(k)
        info = { 'table' => (klass.table_name rescue nil), 'columns' => (cols.call(klass) rescue 'n/a'),
                 'count' => (klass.count rescue 'n/a') }
        info['paperclip'] = (klass.attachment_definitions.transform_values { |v| v.slice(:storage, :path, :url, :bucket).transform_values(&:to_s) } rescue nil)
        info['active_storage'] = (klass.reflect_on_all_attachments.map(&:name) rescue nil)
        info['carrierwave'] = (klass.uploaders.keys rescue nil)
        info['associations'] = (klass.reflect_on_all_associations.map { |a| "#{a.macro} #{a.name}" } rescue nil)
        info['validators'] = (klass.validators.map { |v| "#{v.class.name.split('::').last} #{v.attributes.join(',')} #{v.options.slice(:less_than, :maximum, :in).inspect}" } rescue nil)
        sample = (klass.order(id: :desc).first rescue nil)
        if sample
          info['sample'] = sample.attributes.reject { |c, _| c =~ /content|data|body|blob/i }.transform_values { |v| v.to_s[0, 80] }
        end
        docs[k] = info
      end
      docs['paperclip_default_storage'] = (Paperclip::Attachment.default_options[:storage].to_s rescue nil)
      docs['active_storage_service'] = (Rails.application.config.active_storage.service.to_s rescue nil)
      docs['rails'] = (Rails.version rescue nil)
      out['docs'] = docs

      'PDC probe: ' + JSON.generate(out)
    rescue => e
      "PDC probe failed: #{e.class}: #{e.message} @ #{Array(e.backtrace).first(3).join(' | ')}"
    end
  probe_result
RUBY

File.write(out_path, script)
abort 'generated script does not end with probe_result' unless File.read(out_path).rstrip.end_with?('probe_result')
puts "Wrote #{out_path} (#{File.size(out_path)} bytes)"
