#!/usr/bin/env ruby
# Builds a paste-in script that writes PDC stencil elements (the repo copy,
# with its PDC:ELEMENT marker) into existing elements of stencils PDC doesn't
# own. No repo access needed in Fluxx: element texts are embedded.
#
#   ruby deploy/tools/build_one_off_stencils.rb [OUT]   (default DEV/one-off-stencils.rb)
#
# The generated script:
# - only replaces the `text` of an element it can identify (by marker, or by
#   fingerprints when it has no marker yet); every other byte of the stencil
#   is kept when possible
# - never adds or moves elements (a missing element is reported)
# - dry_run = true by default; `targets` limits it to specific
#   element/stencil pairs
# - returns each replaced element's old text after "backup:"

require 'json'
require 'zlib'
require 'base64'

ROOT = File.expand_path('../..', __dir__)
out_path = File.expand_path(ARGV[0] || 'DEV/one-off-stencils.rb', ROOT)

def strip_ruby(src)
  src.lines.reject { |l| l.strip.empty? || l =~ /\A\s*#/ }.join
end

scope = JSON.parse(File.read(File.join(ROOT, 'deploy/pdc-scope.json'), encoding: 'UTF-8'))
elements = scope['stencil_elements'].map do |s|
  s.merge('text' => File.read(File.join(ROOT, s['path']), encoding: 'UTF-8'))
end
packed = Base64.strict_encode64(Zlib::Deflate.deflate(JSON.generate('scope' => scope, 'elements' => elements), Zlib::BEST_COMPRESSION))
lib = strip_ruby(File.read(File.join(ROOT, 'deploy/installer/PDC Installer Lib.rb'), encoding: 'UTF-8'))

script = <<~RUBY
  # ONE-OFF PDC STENCIL ELEMENTS (generated by deploy/tools/build_one_off_stencils.rb)
  # Writes the repo copy (with its PDC:ELEMENT marker) into matching elements.
  #   dry_run = false   write
  #   targets           [[element_id, stencil_id], ...] to limit what's written; [] = every PDC element found
  # Old element texts come back after "backup:". The last line of this script must be: stencil_result
  dry_run = true
  targets = [['stencil-container-readonly', 26253]]
  require 'json'
  require 'time'
  require 'zlib'
  require 'base64'
  require 'cgi'
  pdc_stencils = JSON.parse(Zlib::Inflate.inflate(Base64.decode64(#{packed.inspect})).force_encoding('UTF-8'))
RUBY
script << lib
script << <<~'RUBY'
  stencil_result =
    begin
      scope = pdc_stencils['scope']
      specs = pdc_stencils['elements']
      marker_re = Regexp.new(scope['markers']['element_regex'])
      log = Hash.new { |h, k| h[k] = [] }
      backup = {}

      # Which spec ids an element's text identifies as (marker first, then fingerprints)
      identify = lambda do |text, model_type|
        decoded = CGI.unescapeHTML(text)
        m = text.match(marker_re) || decoded.match(marker_re)
        next [m[1]] if m
        specs.select do |s|
          s['host_model_types'].include?(model_type) &&
            [text, decoded].any? { |t| s['include'].all? { |f| t.include?(f) } && s['exclude'].none? { |f| t.include?(f) } }
        end.map { |s| s['id'] }
      end

      # The same string as it appears inside the stored JSON, in the encodings Fluxx may have used
      encodings = lambda do |str|
        plain = JSON.generate(str)[1..-2]
        html = plain.gsub('<', '<').gsub('>', '>').gsub('&', '&')
        [plain, html].uniq
      end

      stencil_ids = targets.empty? ? nil : targets.map { |_, sid| sid }.uniq
      rel = Stencil.where(model_type: specs.flat_map { |s| s['host_model_types'] }.uniq, deleted_at: nil)
      rel = rel.where(id: stencil_ids) if stencil_ids
      rel.each do |st|
        raw = st['json'].to_s
        doc = JSON.parse(raw)
        changes = []
        lib[:stencil_elements].call(raw).each do |entry|
          text = lib[:element_text].call(entry['element'])
          next if text.nil?
          ids = identify.call(text, st.model_type)
          next if ids.empty?
          where = "#{ids.join('/')} @ stencil #{st.id} (#{st.name.to_s.strip}) trail #{entry['trail'].inspect}"
          if ids.size > 1
            log['ambiguous (left alone)'] << where
            next
          end
          id = ids.first
          next unless targets.empty? || targets.include?([id, st.id])
          spec = specs.find { |s| s['id'] == id }
          text_ok = lib[:sha].call(text) == lib[:sha].call(spec['text'])
          config_bad = lib[:element_config_problems].call(entry['element'], scope['element_required_config'])
          if text_ok && config_bad.empty?
            log['ok'] << where
            next
          end
          where = "#{where} [#{[text_ok ? nil : 'text', *config_bad].compact.join(', ')}]"
          changes << [entry['trail'], text, spec['text'], where, config_bad.any?]
        end
        next if changes.empty?
        if changes.map { |c| c[0] }.uniq.size != changes.size
          changes.each { |c| log['duplicate trail (left alone)'] << c[3] }
          next
        end
        if dry_run
          changes.each { |c| log['would write'] << c[3] }
          next
        end

        # Minimal edit: swap only each element's encoded text inside the stored JSON.
        # If any swap isn't unambiguous, rewrite the whole document instead (same
        # content, possibly different escaping).
        new_raw = changes.any? { |c| c[4] } ? nil : raw.dup   # settings changes need the document rewritten
        method = 'in place'
        changes.each do |_, old_text, new_text, _|
          break if new_raw.nil?
          pair = encodings.call(old_text).zip(encodings.call(new_text)).find { |old_enc, _| new_raw.scan(old_enc).size == 1 }
          if pair.nil?
            new_raw = nil
            break
          end
          new_raw = new_raw.sub(pair[0]) { pair[1] }
        end
        if new_raw.nil?
          changes.each do |trail, _, new_text, _|
            cfg = trail.inject(doc) { |n, i| n['elements'][i] }['config']
            cfg['text'] = new_text
            # Write settings in forms Fluxx already uses: true for on, "0" for off
            (scope['element_required_config'] || {}).each { |k, want| cfg[k] = want ? true : '0' unless lib[:truthy].call(cfg[k]) == want }
          end
          new_raw = JSON.generate(doc)
          method = 'whole document rewritten'
        end

        # Verify before saving: every changed element now holds exactly the repo text
        check = JSON.parse(new_raw)
        bad = changes.reject do |trail, _, new_text, _|
          node = trail.inject(check) { |n, i| n['elements'][i] }
          node['config']['text'] == new_text && lib[:element_config_problems].call(node, scope['element_required_config']).empty?
        end
        raise "verification failed for #{bad.map { |c| c[3] }.join('; ')}; nothing saved" unless bad.empty?

        changes.each { |trail, old_text, _, where| backup[where] = { 'stencil_id' => st.id, 'trail' => trail, 'text' => old_text } }
        st['json'] = new_raw
        st.save!
        changes.each { |c| log["wrote (#{method})"] << c[3] }
      end

      targets.each do |id, sid|
        hit = log.values.flatten.any? { |w| w.start_with?("#{id} @ stencil #{sid} ") }
        log['target not found'] << "#{id} @ stencil #{sid}" unless hit
      end
      summary = log.map { |k, v| "#{k} #{v.size}" }.join(', ')
      detail = log.reject { |k, _| k == 'ok' }.map { |k, v| "#{k}: #{v.join('; ')}" }.join(' | ')
      saved = backup.empty? ? '' : ' || backup: ' + lib[:pack_export].call('at' => Time.now.utc.iso8601, 'elements' => backup)
      "PDC stencils (#{dry_run ? 'DRY RUN, nothing written' : 'WRITE'}): #{summary}#{detail.empty? ? '' : ' || ' + detail}#{saved}"
    rescue => e
      "PDC stencils failed: #{e.class}: #{e.message} @ #{Array(e.backtrace).first(3).join(' | ')}"
    end
  stencil_result
RUBY

File.write(out_path, script)
abort 'generated script does not end with stencil_result' unless File.read(out_path).rstrip.end_with?('stencil_result')
puts "Wrote #{out_path} (#{File.size(out_path)} bytes, #{script.lines.size} lines, #{elements.size} elements embedded)"
