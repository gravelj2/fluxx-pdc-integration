#!/usr/bin/env ruby
# Builds a single paste-in validation script that needs no repo access: it
# embeds deploy/pdc-manifest.json (compressed) and PDC Installer Lib, then runs
# the same comparison as PDC Validate Install. Read-only, except that it saves
# its results to validate_results on the deploy record it runs on.
#
#   ruby deploy/tools/build_one_off_validate.rb [OUT]   (default DEV/one-off-validate.rb)
#
# Paste the output into a temporary method on the deploy model and run it. It
# returns a one-line summary followed by "PDCEXPORT1:..."; save that and run
#   ruby deploy/tools/pdc_manifest.rb report FILE
# to read the full report.

require 'json'
require 'zlib'
require 'base64'

ROOT = File.expand_path('../..', __dir__)
out_path = File.expand_path(ARGV[0] || 'DEV/one-off-validate.rb', ROOT)

def strip_ruby(src)
  src.lines.reject { |l| l.strip.empty? || l =~ /\A\s*#/ }.join
end

manifest = JSON.generate(JSON.parse(File.read(File.join(ROOT, 'deploy/pdc-manifest.json'), encoding: 'UTF-8')))
packed = Base64.strict_encode64(Zlib::Deflate.deflate(manifest, Zlib::BEST_COMPRESSION))
lib = strip_ruby(File.read(File.join(ROOT, 'deploy/installer/PDC Installer Lib.rb'), encoding: 'UTF-8'))

script = <<~RUBY
  # ONE-OFF PDC VALIDATE (generated by deploy/tools/build_one_off_validate.rb; read-only)
  # Embeds the manifest, so nothing is fetched. The last line of this script must be: validate_result
  require 'json'
  require 'time'
  require 'zlib'
  require 'base64'
  pdc_manifest = JSON.parse(Zlib::Inflate.inflate(Base64.decode64(#{packed.inspect})).force_encoding('UTF-8'))
RUBY
script << lib
script << <<~'RUBY'
  validate_result =
    begin
      live = lib[:collect].call(pdc_manifest['scope'], false)
      rows = lib[:validate].call(pdc_manifest, live, model)
      report = lib[:summarize].call(
        rows,
        'validated_at' => Time.now.utc.iso8601,
        'ref' => 'one-off (embedded manifest)',
        'manifest_source' => pdc_manifest['source'],
        'deploy_model' => model.class.name,
        'warnings' => Array(live['warnings'])
      )
      record = lib[:results_record].call('Validation', 'read-only, embedded manifest', rows,
                                         'warnings' => Array(live['warnings']))
      saved = lib[:store_results].call(model, 'validate_results', record, true)
      summary = report['summary'].sort.map { |k, v| "#{k} #{v}" }.join(', ')
      "PDC validation (#{saved}): #{summary} || " + lib[:pack_export].call(report)
    rescue => e
      "PDC validate failed: #{e.class}: #{e.message} @ #{Array(e.backtrace).first(3).join(' | ')}"
    end
  validate_result
RUBY

File.write(out_path, script)
abort 'generated script does not end with validate_result' unless File.read(out_path).rstrip.end_with?('validate_result')
puts "Wrote #{out_path} (#{File.size(out_path)} bytes, #{script.lines.size} lines)"
