#!/usr/bin/env ruby
# Builds a paste-in cleanup script: finds "extras" (methods, workflow states
# and workflow buttons on the three PDC models that the manifest doesn't list)
# and soft-deletes only the ones you name. No repo access needed in Fluxx.
#
#   ruby deploy/tools/build_one_off_cleanup.rb [OUT]   (default DEV/one-off-cleanup.rb)
#
# Never touched: stencils and stencil elements, fields, dropdown options,
# themes, models, the deploy model, anything on GrantRequest or other models,
# secret methods, and methods matching the scope's exclusions (zzz*, known
# test methods).
#
# The generated script:
# - always lists every extra it finds
# - soft-deletes (sets deleted_at) only keys listed in remove_keys, and only
#   when dry_run = false
# - returns each removed record's contents after "backup:", and saves its
#   results to cleanup_results on the deploy record it runs on

require 'json'
require 'zlib'
require 'base64'

ROOT = File.expand_path('../..', __dir__)
out_path = File.expand_path(ARGV[0] || 'DEV/one-off-cleanup.rb', ROOT)

def strip_ruby(src)
  src.lines.reject { |l| l.strip.empty? || l =~ /\A\s*#/ }.join
end

manifest = JSON.parse(File.read(File.join(ROOT, 'deploy/pdc-manifest.json'), encoding: 'UTF-8'))
data = {
  'scope' => manifest['scope'],
  'method_keys' => manifest['methods'].map { |m| m['key'] },
  'state_keys' => manifest['states'].map { |m| m['key'] },
  'event_keys' => manifest['events'].map { |m| m['key'] }
}
packed = Base64.strict_encode64(Zlib::Deflate.deflate(JSON.generate(data), Zlib::BEST_COMPRESSION))
lib = strip_ruby(File.read(File.join(ROOT, 'deploy/installer/PDC Installer Lib.rb'), encoding: 'UTF-8'))

script = <<~RUBY
  # ONE-OFF PDC CLEANUP (generated by deploy/tools/build_one_off_cleanup.rb)
  # Lists methods, states and buttons on the PDC models that the manifest doesn't list.
  #   remove_keys = [...]   keys to soft-delete, copied from a dry run's list; anything not listed stays
  #   dry_run = false       actually remove the listed keys
  # Removed records come back after "backup:". Results are also saved to cleanup_results on this deploy record.
  # The last line of this script must be: cleanup_result
  dry_run = true
  remove_keys = []
  require 'json'
  require 'time'
  require 'zlib'
  require 'base64'
  pdc_cleanup = JSON.parse(Zlib::Inflate.inflate(Base64.decode64(#{packed.inspect})).force_encoding('UTF-8'))
RUBY
script << lib
script << <<~'RUBY'
  cleanup_result =
    begin
      unless dry_run || remove_keys.empty?
        ruby_denied =
          begin
            ActiveRecord::Base.transaction do
              ModelMethod.create!(model_type: model.class.name, method_type: 'method', name: 'PDC Permission Probe', unsafe_dyn_method: "'ok'")
              raise ActiveRecord::Rollback
            end
            nil
          rescue => e
            "#{e.class}: #{e.message}"
          end
        raise "This user cannot save custom Ruby in Fluxx (#{ruby_denied})" if ruby_denied
      end

      scope = pdc_cleanup['scope']
      owned = scope['owned_model_types'].keys
      excluded = (scope['excluded_method_patterns'] || []).map { |p| Regexp.new(p) }
      secrets = scope['secret_methods'] || []
      log = Hash.new { |h, k| h[k] = [] }
      removed = {}
      now = Time.now

      extra = lambda do |rec, key, fields|
        unless remove_keys.include?(key)
          log['extra (kept)'] << key
          next
        end
        unless rec.class.column_names.include?('deleted_at')
          log['cannot soft-delete (left alone)'] << key
          next
        end
        if dry_run
          log['would remove'] << key
          next
        end
        removed[key] = fields.each_with_object({ 'id' => rec.id }) { |f, h| h[f] = rec[f] }
        rec.deleted_at = now
        rec.save!
        log['removed'] << key
      end

      ModelMethod.where(model_type: owned, deleted_at: nil).each do |mm|
        key = "#{mm.model_type}##{mm.name}"
        next if pdc_cleanup['method_keys'].include?(key) || secrets.include?(mm.name) || excluded.any? { |re| mm.name =~ re }
        extra.call(mm, key, %w[name method_type unsafe_dyn_method])
      end
      ModelTheme.where(model_type: owned, deleted_at: nil).each do |t|
        MachineWorkflow.where(model_theme_id: t.id, deleted_at: nil).each do |wf|
          MachineEvent.where(machine_workflow_id: wf.id, deleted_at: nil).each do |ev|
            key = "#{t.model_type}/#{t.name}>#{ev.button_name}"
            extra.call(ev, key, %w[button_name to_state_id unsafe_guard]) unless pdc_cleanup['event_keys'].include?(key)
          end
        end
      end
      MachineState.where(model_type: owned, deleted_at: nil).each do |st|
        key = "#{st.model_type}:#{st.name}"
        extra.call(st, key, %w[name unsafe_before_validation_enter unsafe_after_enter]) unless pdc_cleanup['state_keys'].include?(key)
      end
      found = log.values.flatten
      remove_keys.each { |k| log['key not found (nothing removed)'] << k unless found.include?(k) }
      log['no extras found'] << 'the PDC models match the manifest' if found.empty? && remove_keys.empty?

      packed = removed.empty? ? nil : lib[:pack_export].call('at' => now.utc.iso8601, 'removed' => removed)
      mode = dry_run ? 'dry run, nothing removed' : 'remove listed keys'
      record = lib[:results_record].call('Cleanup', mode, lib[:log_entries].call(log), packed ? { 'backup' => packed } : {})
      stored = lib[:store_results].call(model, 'cleanup_results', record, true)
      summary = log.map { |k, v| "#{k} #{v.size}" }.join(', ')
      detail = log.map { |k, v| "#{k}: #{v.join('; ')}" }.join(' | ')
      "PDC cleanup (#{mode}; #{stored}): #{summary} || #{detail}#{packed ? ' || backup: ' + packed : ''}"
    rescue => e
      failed = "#{e.class}: #{e.message} @ #{Array(e.backtrace).first(3).join(' | ')}"
      lib[:store_results].call(model, 'cleanup_results', lib[:results_record].call('Cleanup', 'failed', [], 'error' => failed), true) rescue nil
      "PDC cleanup failed: #{failed}"
    end
  cleanup_result
RUBY

File.write(out_path, script)
abort 'generated script does not end with cleanup_result' unless File.read(out_path).rstrip.end_with?('cleanup_result')
puts "Wrote #{out_path} (#{File.size(out_path)} bytes, #{script.lines.size} lines)"
