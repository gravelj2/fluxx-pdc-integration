#!/usr/bin/env ruby
# Builds a paste-in install script for the PDC's own models (phase 1: code and
# workflow). No repo access needed in Fluxx: the manifest entries and bodies
# are embedded (compressed).
#
#   ruby deploy/tools/build_one_off_install.rb [OUT]   (default DEV/one-off-install.rb)
#
# Handles, in this order:
#   methods  create missing; overwrite if they differ (overwrite_differs)
#   themes   Before New / After Create code (themes themselves must exist)
#   states   restore soft-deleted or create missing; overwrite settings and hooks
#   buttons  restore soft-deleted or create missing (from-states, order, role);
#            overwrite target, from-states, guard, filter, flags
#   extras   with remove_extras, soft-delete methods, states and buttons on the
#            PDC models that the manifest doesn't list
# Not yet: models, fields/options, stencils, permissions, the GrantRequest
# `granted` block (reported by Validate; handled in later phases).
#
# Safety rules, in the generated script:
# - dry_run = true by default: lists what it would do, writes nothing.
# - Existing records are only changed with overwrite_differs = true; restoring
#   or creating MISSING records needs only dry_run = false.
# - Every replaced value and every removed record comes back in the result,
#   after "backup:", so nothing is lost.
# - Removal is a soft delete (deleted_at); records without that column are left alone.
# - Secret methods are never touched. Only the PDC's own models are changed.
# - Stops before writing if this user can't save custom Ruby.

require 'json'
require 'zlib'
require 'base64'

ROOT = File.expand_path('../..', __dir__)
out_path = File.expand_path(ARGV[0] || 'DEV/one-off-install.rb', ROOT)

def strip_ruby(src)
  src.lines.reject { |l| l.strip.empty? || l =~ /\A\s*#/ }.join
end

def body(path)
  path && File.read(File.join(ROOT, path), encoding: 'UTF-8')
end

manifest = JSON.parse(File.read(File.join(ROOT, 'deploy/pdc-manifest.json'), encoding: 'UTF-8'))
data = {
  'scope' => manifest['scope'],
  'methods' => manifest['methods'].reject { |m| m['secret'] }.map do |m|
    m.slice('key', 'model_type', 'name', 'method_type').merge('body' => body(m['body_path']))
  end,
  'themes' => manifest['themes'].map do |t|
    t.slice('key', 'model_type', 'name').merge('before_new' => body(t['before_new_path']), 'after_create' => body(t['after_create_path']))
  end,
  'states' => manifest['states'].map do |s|
    s.slice('key', 'model_type', 'name', 'description', 'state_type', 'state_order', 'allowed_roles')
     .merge('before_validation_enter' => body(s['before_validation_enter_path']), 'after_enter' => body(s['after_enter_path']))
  end,
  'events' => manifest['events'].map do |e|
    e.slice('key', 'model_type', 'theme', 'button_name', 'name', 'to_state', 'from_states', 'is_validation_suppressed',
            'guard_strategy', 'filter').merge('guard' => body(e['guard_path']))
  end
}
packed = Base64.strict_encode64(Zlib::Deflate.deflate(JSON.generate(data), Zlib::BEST_COMPRESSION))
lib = strip_ruby(File.read(File.join(ROOT, 'deploy/installer/PDC Installer Lib.rb'), encoding: 'UTF-8'))

script = <<~RUBY
  # ONE-OFF PDC INSTALL, PHASE 1 (generated by deploy/tools/build_one_off_install.rb)
  # Methods, theme hooks, states and buttons on the PDC models. Not yet: fields, stencils.
  #   dry_run = false            write (restore/create missing records)
  #   overwrite_differs = true   also replace records that differ
  #   remove_extras = true       also soft-delete PDC methods/states/buttons not in the manifest
  #   event_role_name            role for restored/created buttons; nil = the role the workflow's other buttons use
  # Replaced and removed values come back after "backup:". The last line of this script must be: install_result
  dry_run = true
  overwrite_differs = false
  remove_extras = false
  event_role_name = nil
  require 'json'
  require 'time'
  require 'zlib'
  require 'base64'
  pdc_install = JSON.parse(Zlib::Inflate.inflate(Base64.decode64(#{packed.inspect})).force_encoding('UTF-8'))
RUBY
script << lib
script << <<~'RUBY'
  install_result =
    begin
      ruby_denied =
        begin
          ActiveRecord::Base.transaction do
            ModelMethod.create!(model_type: model.class.name, method_type: 'method', name: 'PDC Permission Probe', unsafe_dyn_method: "'ok'")
            raise ActiveRecord::Rollback
          end
          nil
        rescue => e
          "#{e.class}: #{e.message}"
        end
      raise "This user cannot save custom Ruby in Fluxx (#{ruby_denied})" if ruby_denied

      scope = pdc_install['scope']
      owned = scope['owned_model_types'].keys
      excluded = (scope['excluded_method_patterns'] || []).map { |p| Regexp.new(p) }
      secrets = scope['secret_methods'] || []
      log = Hash.new { |h, k| h[k] = [] }
      backup = { 'replaced' => {}, 'removed' => {} }
      now = Time.now

      # Columns whose value differs from what's wanted. Code columns compare
      # normalized text, so whitespace-only drift doesn't count.
      diffs = lambda do |rec, desired|
        desired.select do |col, val|
          col.start_with?('unsafe_') ? lib[:sha].call(rec[col]) != lib[:sha].call(val) : rec[col] != val
        end.keys
      end
      # Bring an existing record in line with the manifest (only with overwrite_differs).
      reconcile = lambda do |key, rec, desired, extra_changes = [], apply_extra = nil|
        changed = diffs.call(rec, desired)
        all = changed + extra_changes
        if all.empty?
          log['ok'] << key
        elsif !overwrite_differs
          log['differs (left alone)'] << "#{key} [#{all.join(', ')}]"
        elsif dry_run
          log['would overwrite'] << "#{key} [#{all.join(', ')}]"
        else
          backup['replaced'][key] = changed.each_with_object({}) { |c, h| h[c] = rec[c] }
          changed.each { |c| rec[c] = desired[c] }
          rec.save! unless changed.empty?
          apply_extra.call if apply_extra
          log['overwrote'] << "#{key} [#{all.join(', ')}]"
        end
      end
      soft_delete = lambda do |rec, key, fields|
        unless rec.class.column_names.include?('deleted_at')
          log['extra, cannot soft-delete (left alone)'] << key
          next
        end
        unless dry_run
          backup['removed'][key] = fields.each_with_object({ 'id' => rec.id }) { |f, h| h[f] = rec[f] }
          rec.deleted_at = now
          rec.save!
        end
        log[dry_run ? 'would remove' : 'removed'] << key
      end

      # Methods
      pdc_install['methods'].each do |m|
        live = ModelMethod.where(model_type: m['model_type'], name: m['name'], deleted_at: nil).first
        if live
          reconcile.call(m['key'], live, { 'method_type' => m['method_type'], 'unsafe_dyn_method' => m['body'] })
        elsif dry_run
          log['would create'] << m['key']
        else
          ModelMethod.create!(model_type: m['model_type'], method_type: m['method_type'], name: m['name'], unsafe_dyn_method: m['body'])
          log['created'] << m['key']
        end
      end

      # Theme hooks
      pdc_install['themes'].each do |t|
        rec = ModelTheme.where(model_type: t['model_type'], name: t['name'], deleted_at: nil).first
        if rec.nil?
          log['theme missing (not handled yet)'] << t['key']
          next
        end
        reconcile.call(t['key'], rec, { 'unsafe_before_new_block' => t['before_new'], 'unsafe_after_create_block' => t['after_create'] })
      end

      # States: restore a soft-deleted one (keeps its id, so buttons pointing at it work again) or create
      state_desired = lambda do |s|
        { 'description' => s['description'], 'state_type' => s['state_type'], 'state_order' => s['state_order'],
          'allowed_roles' => s['allowed_roles'], 'unsafe_before_validation_enter' => s['before_validation_enter'],
          'unsafe_after_enter' => s['after_enter'] }
      end
      pdc_install['states'].each do |s|
        live = MachineState.where(model_type: s['model_type'], name: s['name'], deleted_at: nil).first
        if live
          reconcile.call(s['key'], live, state_desired.call(s))
          next
        end
        gone = MachineState.where(model_type: s['model_type'], name: s['name']).where.not(deleted_at: nil).order(deleted_at: :desc).first
        if dry_run
          log[gone ? 'would restore' : 'would create'] << s['key']
          next
        end
        rec = gone || MachineState.new(model_type: s['model_type'], name: s['name'])
        rec.deleted_at = nil if gone
        state_desired.call(s).each { |c, v| rec[c] = v }
        rec.save!
        log[gone ? 'restored' : 'created'] << s['key']
      end

      # Buttons
      state_id = lambda { |mt, name| MachineState.where(model_type: mt, name: name, deleted_at: nil).first&.id }
      pick_role = lambda do |wf|
        named = event_role_name || lib[:selected_role_name].call(model)
        role = named && Role.where(name: named, deleted_at: nil).first
        role || begin
          ids = MachineEventRole.where(machine_event_id: MachineEvent.where(machine_workflow_id: wf.id, deleted_at: nil).pluck(:id)).pluck(:role_id)
          common = ids.group_by { |i| i }.max_by { |_, v| v.size }
          common && Role.find_by(id: common.first)
        end
      end
      pdc_install['events'].each do |e|
        theme = ModelTheme.where(model_type: e['model_type'], name: e['theme'], deleted_at: nil).first
        wf = theme && MachineWorkflow.where(model_theme_id: theme.id, deleted_at: nil).first
        if wf.nil?
          log['workflow missing (not handled yet)'] << e['key']
          next
        end
        to_id = state_id.call(e['model_type'], e['to_state'])
        want_from = e['from_states'].map { |name, order| [state_id.call(e['model_type'], name), order] }
        if to_id.nil? || want_from.any? { |id, _| id.nil? }
          log[dry_run ? 'waits on a state above being restored or created' : 'skipped, a state it needs is missing'] << e['key']
          next
        end
        desired = { 'to_state_id' => to_id, 'is_validation_suppressed' => e['is_validation_suppressed'],
                    'guard_strategy' => e['guard_strategy'], 'filter' => e['filter'], 'unsafe_guard' => e['guard'] }
        want_from = want_from.sort
        set_links = lambda do |ev|
          have = MachineEventFromState.where(machine_event_id: ev.id).map { |f| [f.from_state_id, f.button_order] }.sort
          if have != want_from
            backup['replaced']["#{e['key']} from_states"] = have unless have.empty?
            MachineEventFromState.where(machine_event_id: ev.id).destroy_all
            want_from.each { |id, order| MachineEventFromState.create!(machine_event_id: ev.id, from_state_id: id, button_order: order) }
          end
          if MachineEventRole.where(machine_event_id: ev.id).empty? && (role = pick_role.call(wf))
            MachineEventRole.create!(machine_event_id: ev.id, role_id: role.id)
          end
        end

        live = MachineEvent.where(machine_workflow_id: wf.id, button_name: e['button_name'], deleted_at: nil).first
        if live
          have = MachineEventFromState.where(machine_event_id: live.id).map { |f| [f.from_state_id, f.button_order] }.sort
          extra = []
          extra << 'from_states' if have != want_from
          extra << 'role' if MachineEventRole.where(machine_event_id: live.id).empty?
          reconcile.call(e['key'], live, desired, extra, -> { set_links.call(live) })
          next
        end
        gone = MachineEvent.where(machine_workflow_id: wf.id, button_name: e['button_name']).where.not(deleted_at: nil).order(deleted_at: :desc).first
        if dry_run
          log[gone ? 'would restore' : 'would create'] << e['key']
          next
        end
        rec = gone || MachineEvent.new(machine_workflow_id: wf.id, button_name: e['button_name'])
        rec.deleted_at = nil if gone
        desired.each { |c, v| rec[c] = v }
        rec.save!
        set_links.call(rec)
        log[gone ? 'restored' : 'created'] << e['key']
      end

      # Extras: PDC-model records the manifest doesn't list
      if remove_extras
        known = pdc_install['methods'].map { |m| m['key'] }
        ModelMethod.where(model_type: owned, deleted_at: nil).each do |mm|
          key = "#{mm.model_type}##{mm.name}"
          next if known.include?(key) || secrets.include?(mm.name) || excluded.any? { |re| mm.name =~ re }
          soft_delete.call(mm, key, %w[name method_type unsafe_dyn_method])
        end
        known_events = pdc_install['events'].map { |e| e['key'] }
        ModelTheme.where(model_type: owned, deleted_at: nil).each do |t|
          MachineWorkflow.where(model_theme_id: t.id, deleted_at: nil).each do |wf|
            MachineEvent.where(machine_workflow_id: wf.id, deleted_at: nil).each do |ev|
              key = "#{t.model_type}/#{t.name}>#{ev.button_name}"
              soft_delete.call(ev, key, %w[button_name to_state_id unsafe_guard]) unless known_events.include?(key)
            end
          end
        end
        known_states = pdc_install['states'].map { |s| s['key'] }
        MachineState.where(model_type: owned, deleted_at: nil).each do |st|
          key = "#{st.model_type}:#{st.name}"
          soft_delete.call(st, key, %w[name unsafe_before_validation_enter unsafe_after_enter]) unless known_states.include?(key)
        end
      end

      summary = log.map { |k, v| "#{k} #{v.size}" }.join(', ')
      detail = log.reject { |k, _| k == 'ok' }.map { |k, v| "#{k}: #{v.join('; ')}" }.join(' | ')
      saved = backup['replaced'].empty? && backup['removed'].empty? ? '' : ' || backup: ' + lib[:pack_export].call(backup.merge('at' => now.utc.iso8601))
      flags = dry_run ? 'DRY RUN, nothing written' : "WRITE#{overwrite_differs ? ', overwrite' : ''}#{remove_extras ? ', remove extras' : ''}"
      "PDC install (#{flags}): #{summary}#{detail.empty? ? '' : ' || ' + detail}#{saved}"
    rescue => e
      "PDC install failed: #{e.class}: #{e.message} @ #{Array(e.backtrace).first(3).join(' | ')}"
    end
  install_result
RUBY

File.write(out_path, script)
abort 'generated script does not end with install_result' unless File.read(out_path).rstrip.end_with?('install_result')
puts "Wrote #{out_path} (#{File.size(out_path)} bytes, #{script.lines.size} lines; " \
     "#{data['methods'].size} methods, #{data['themes'].size} themes, #{data['states'].size} states, #{data['events'].size} buttons)"
